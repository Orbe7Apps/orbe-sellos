export { IDIOMA };
export function tn(k, vars = {}) {
  let s = (T[IDIOMA] && T[IDIOMA][k]) ?? T.es[k] ?? k;
  if (typeof s !== 'string') return s;
  for (const v in vars) s = s.split('{' + v + '}').join(vars[v]);
  return s;
}
// Elige el texto en singular (n = 1) o plural.
export const tnn = (n, uno, varios, vars = {}) => n === 1 ? tn(uno, vars) : tn(varios, { n, ...vars });
