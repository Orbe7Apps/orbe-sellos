export function idioma() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && T[q]) return q;
  for (const l of navigator.languages || [navigator.language || 'es']) { const k = String(l).slice(0, 2).toLowerCase(); if (T[k]) return k; }
  return 'es';
}
export const IDIOMA = idioma();
export function t(k, vars = {}, lang = IDIOMA) {
  let s = (T[lang] && T[lang][k]) ?? T.es[k] ?? k;
  for (const v in vars) s = s.split('{' + v + '}').join(vars[v]);
  return s;
}
